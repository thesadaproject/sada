#!/usr/bin/env python3
"""Smoke test of the production public pages (https://sadakhutbah.org).

Run after a release (workflow `Prod smoke test`) or by hand:

    python3 scripts/smoke_prod.py                      # check now
    python3 scripts/smoke_prod.py --expect-version 0.1.0-alpha.14 --wait 900

1. Optionally waits until the console reports the expected version on /api/v1/health (Flux deploys the
   release tag a few minutes after the image is built).
2. Checks the public pages the way a visitor's browser would: the page, every .js/.css it references, the
   boot JSON, the JSON endpoints and every export link generated by packages/public (Mois.tsx, Ecran.tsx).

Standard library only. Exit code 0 when everything passes, 1 otherwise (every failure is listed).
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
import urllib.error
import urllib.request
from collections.abc import Callable
from dataclasses import dataclass
from datetime import date, datetime
from html.parser import HTMLParser
from zoneinfo import ZoneInfo

USER_AGENT = "sada-prod-smoke/1"
RANGE_PDF = re.compile(r"^prayer-times-\d{4}-\d{2}-\d{2}_\d{4}-\d{2}-\d{2}\.pdf$")


@dataclass
class Reply:
    status: int
    headers: dict[str, str]
    body: bytes

    @property
    def text(self) -> str:
        return self.body.decode("utf-8", errors="replace")

    @property
    def filename(self) -> str | None:
        m = re.search(r'filename="?([^";]+)"?', self.headers.get("content-disposition", ""))
        return m.group(1) if m else None


def fetch(url: str, timeout: float = 30.0) -> Reply:
    """GET `url`, redirects followed; an HTTP error status is a Reply, a network error is status 0."""
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": "*/*"})
    try:
        with urllib.request.urlopen(request, timeout=timeout) as r:
            return Reply(r.status, {k.lower(): v for k, v in r.headers.items()}, r.read())
    except urllib.error.HTTPError as e:
        return Reply(e.code, {k.lower(): v for k, v in e.headers.items()}, e.read())
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        return Reply(0, {}, str(e).encode())


class _Refs(HTMLParser):
    """Collects the script/stylesheet URLs and the boot JSON of a page."""

    def __init__(self) -> None:
        super().__init__()
        self.refs: list[str] = []
        self.boot: str | None = None
        self._in_boot = False

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "script" and a.get("src"):
            self.refs.append(a["src"])
        elif tag == "script" and a.get("id") == "boot":
            self._in_boot = True
            self.boot = ""
        elif (
            tag == "link"
            and a.get("href")
            and (a.get("rel") == "stylesheet" or a["href"].split("?")[0].endswith(".css"))
        ):
            self.refs.append(a["href"])

    def handle_endtag(self, tag):
        if tag == "script":
            self._in_boot = False

    def handle_data(self, data):
        if self._in_boot and self.boot is not None:
            self.boot += data


def parse_page(html: str) -> tuple[list[str], dict | None]:
    """(.js/.css URLs referenced by the page, boot JSON or None)."""
    parser = _Refs()
    parser.feed(html)
    refs = [r for r in parser.refs if re.search(r"\.(js|css)(\?|$)", r)]
    try:
        boot = json.loads(parser.boot) if parser.boot else None
    except json.JSONDecodeError:
        boot = None
    return list(dict.fromkeys(refs)), boot


def current_month(today: date | None = None) -> str:
    """YYYY-MM in the mosque's timezone (the test mosque is on Europe/Paris)."""
    d = today or datetime.now(ZoneInfo("Europe/Paris")).date()
    return f"{d.year:04d}-{d.month:02d}"


def version_of_tag(tag: str) -> str:
    """`sada-v0.1.0-alpha.14` or `v0.1.0-alpha.14` -> `0.1.0-alpha.14`."""
    return re.sub(r"^(?:.*-)?v(?=\d)", "", tag)


def wait_for_version(
    console: str, expected: str, wait: float, interval: float, sleep: Callable[[float], None] = time.sleep
) -> bool:
    """Poll the console health until it serves `expected`; False when `wait` seconds pass first."""
    deadline = time.monotonic() + wait
    seen = None
    while True:
        r = fetch(f"{console}/api/v1/health", timeout=15)
        try:
            seen = json.loads(r.text).get("version") if r.status == 200 else f"HTTP {r.status}"
        except (json.JSONDecodeError, AttributeError):
            seen = "unreadable"
        if seen == expected:
            print(f"  prod serves {expected}")
            return True
        if time.monotonic() >= deadline:
            print(f"  prod still serves {seen!r}, expected {expected!r}")
            return False
        print(f"  prod serves {seen!r}, waiting for {expected!r}...")
        sleep(interval)


class Suite:
    def __init__(self) -> None:
        self.failures: list[str] = []
        self.count = 0

    def check(self, name: str, ok: bool, detail: str = "") -> bool:
        self.count += 1
        print(f"{'ok  ' if ok else 'FAIL'} {name}" + (f"  ({detail})" if detail and not ok else ""))
        if not ok:
            self.failures.append(f"{name}: {detail}" if detail else name)
        return ok

    def status(self, name: str, url: str, want: int = 200) -> Reply:
        r = fetch(url)
        self.check(f"{name} -> {want}", r.status == want, f"{url} answered {r.status}")
        return r


def run(base: str, slug: str, month: str) -> Suite:
    s = Suite()
    page_url = f"{base}/m/{slug}"
    page = s.status(f"page /m/{slug}", page_url)
    refs, boot = parse_page(page.text) if page.status == 200 else ([], None)
    s.check(
        "page references at least one .js and one .css",
        any(r.endswith(".js") for r in refs) and any(r.endswith(".css") for r in refs),
        str(refs),
    )
    for ref in refs:
        url = ref if ref.startswith("http") else f"{base}{ref}"
        r = s.status(f"asset {ref}", url)
        if r.status == 200:
            s.check(
                f"asset {ref} is not an HTML page",
                "text/html" not in r.headers.get("content-type", ""),
                r.headers.get("content-type", ""),
            )

    s.check(
        "boot JSON present and carries `api`", bool(boot) and bool(boot.get("api")), "no <script id=boot> or no api key"
    )
    api = (boot or {}).get("api") or f"/api/v1/public/mosques/{slug}"
    api_url = f"{base}{api}"

    # JSON endpoints used by the screen and the monthly table
    for label, path in (
        ("prayer-times", "/prayer-times"),
        ("prayer-times?month", f"/prayer-times?month={month}"),
        ("prayer-times/days", f"/prayer-times/days?from={month}-01"),
    ):
        r = s.status(label, f"{api_url}{path}")
        if r.status == 200:
            try:
                json.loads(r.text)
                s.check(f"{label} is JSON", True)
            except json.JSONDecodeError:
                s.check(f"{label} is JSON", False, r.text[:80])

    # monthly page (?month=) and its previous/next links
    s.status(f"page /m/{slug}?month={month}", f"{page_url}?month={month}")

    # export links generated by Mois.tsx / Ecran.tsx
    export = f"{api_url}/prayer-times/export"
    csv = s.status("export csv (current month)", f"{export}?format=csv&month={month}")
    s.check("csv filename", csv.filename == f"prayer-times-{month}.csv", str(csv.filename))
    s.check("csv has content", csv.status == 200 and len(csv.body) > 100 and b"\n" in csv.body, csv.text[:80])
    pdf = s.status("export pdf (current month)", f"{export}?format=pdf&month={month}")
    s.check("pdf filename", pdf.filename == f"prayer-times-{month}.pdf", str(pdf.filename))
    s.check("pdf is a PDF", pdf.body.startswith(b"%PDF"), pdf.text[:40])
    ram = s.status("export pdf (ramadan)", f"{export}?format=pdf&ramadan=1")
    s.check("ramadan filename is a date range", bool(RANGE_PDF.match(ram.filename or "")), str(ram.filename))
    s.check("ramadan pdf is a PDF", ram.body.startswith(b"%PDF"), ram.text[:40])
    return s


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base", default="https://sadakhutbah.org", help="public site (default %(default)s)")
    p.add_argument("--console", default="https://console.sadakhutbah.org", help="origin serving /api/v1/health")
    p.add_argument("--slug", default="test", help="mosque used for the checks (default %(default)s)")
    p.add_argument("--month", default=None, help="YYYY-MM to check (default: current month in Paris)")
    p.add_argument(
        "--expect-version",
        default=None,
        help="wait until /api/v1/health reports it (a tag like sada-v0.1.0 is accepted)",
    )
    p.add_argument("--wait", type=float, default=900, help="seconds to wait for the version (default %(default)s)")
    p.add_argument("--interval", type=float, default=20, help="seconds between two polls (default %(default)s)")
    a = p.parse_args(argv)

    if a.expect_version:
        want = version_of_tag(a.expect_version)
        print(f"waiting for {a.console} to serve {want} (max {a.wait:.0f}s)")
        if not wait_for_version(a.console.rstrip("/"), want, a.wait, a.interval):
            print("FAILED: the release is not deployed in time", file=sys.stderr)
            return 1
    suite = run(a.base.rstrip("/"), a.slug, a.month or current_month())
    print(f"\n{suite.count - len(suite.failures)}/{suite.count} checks passed")
    if suite.failures:
        print("FAILED:\n  - " + "\n  - ".join(suite.failures), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
